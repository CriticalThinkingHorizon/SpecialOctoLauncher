from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math
import struct

root = Path(__file__).resolve().parent
(root / 'assets').mkdir(exist_ok=True)
(root / 'shaders').mkdir(exist_ok=True)

FONT_CANDIDATES = [
    str((root.parent.parent / 'fonts' / 'fixedsys.ttf').resolve()),
    'C:/Windows/Fonts/consola.ttf',
    'C:/Windows/Fonts/cour.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
]
font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
if font_path is None:
    raise SystemExit('No monospace TrueType font found.')

FONT_SIZE = 30
ATLAS_W, ATLAS_H = 1024, 2048
FIRST, LAST = 32, 126

font = ImageFont.truetype(font_path, FONT_SIZE)
ascent, descent = font.getmetrics()
CELL_W = math.ceil(font.getlength('M')) + 2
CELL_H = ascent + descent + 2
COLS = ATLAS_W // CELL_W

atlas = Image.new('L', (ATLAS_W, ATLAS_H), 0)
draw = ImageDraw.Draw(atlas)
for code in range(FIRST, LAST + 1):
    idx = code - FIRST
    x = (idx % COLS) * CELL_W
    y = (idx // COLS) * CELL_H
    draw.text((x + 1, y + 1), chr(code), font=font, fill=255)

(root / 'assets/text.bin').write_bytes(atlas.tobytes())
(root / 'shaders/text.glsl').write_text(
    '// Generated by assets.py. Do not edit.\n'
    f'const int GLYPH_W = {CELL_W};\n'
    f'const int GLYPH_H = {CELL_H};\n'
    f'const int GLYPH_COLS = {COLS};\n'
    f'const uint GLYPH_FIRST = {FIRST}u;\n'
    f'const uint GLYPH_COUNT = {LAST - FIRST + 1}u;\n'
)

# Initial state (1024 bytes)
state = bytearray(1024)
# c.game: x = state (0=play), y = level (0), z = timer/substate (0), w = score/gems (0)
state[784:800] = struct.pack('<IIII', 0, 0, 0, 0)
# c.flow: ball pos X (1.5), pos Y (1.5), vel X (0.0), vel Y (0.0)
state[816:832] = struct.pack('<ffff', 1.5, 1.5, 0.0, 0.0)
# c.piece: rot X (0), rot Y (0), scale (1.0), trigger (0)
state[800:816] = struct.pack('<fffi', 0.0, 0.0, 1.0, 0)
# c.transition: tilt X (0.0), tilt Y (0.0), tare X (0.0), tare Y (0.0)
state[960:976] = struct.pack('<ffff', 0.0, 0.0, 0.0, 0.0)
(root / 'assets/state.bin').write_bytes(bytes(state))

# Generate high-contrast Gyro 3D Tilt Maze icon (256x256)
im = Image.new('RGBA', (256, 256), (15, 12, 10, 255))
d = ImageDraw.Draw(im)

# Outer rounded wooden frame
d.rounded_rectangle((12, 12, 244, 244), radius=28, fill=(35, 24, 18), outline=(190, 140, 75), width=6)
# Inner labyrinth floor
d.rounded_rectangle((28, 28, 228, 228), radius=16, fill=(55, 38, 28), outline=(130, 90, 50), width=4)

# Maze walls preview
walls = [
    [(40, 70), (140, 70)],
    [(140, 70), (140, 130)],
    [(80, 110), (80, 190)],
    [(80, 190), (180, 190)],
    [(170, 70), (216, 70)],
    [(170, 110), (216, 110)],
    [(120, 150), (120, 190)],
    [(180, 150), (216, 150)],
]
for p1, p2 in walls:
    d.line([p1, p2], fill=(220, 180, 110), width=8)

# Hazard Holes (dark sunken pits)
holes = [(60, 150), (180, 90), (150, 170)]
for hx, hy in holes:
    d.ellipse((hx - 12, hy - 12, hx + 12, hy + 12), fill=(10, 8, 8), outline=(80, 50, 30), width=3)

# Goal Portal (glowing cyan circle)
d.ellipse((202 - 14, 202 - 14, 202 + 14, 202 + 14), fill=(20, 120, 180), outline=(80, 220, 255), width=4)
d.ellipse((202 - 6, 202 - 6, 202 + 6, 202 + 6), fill=(160, 240, 255))

# 3D Chrome Ball with specular highlight
bx, by, br = 105, 90, 18
# Drop shadow
d.ellipse((bx - br + 4, by - br + 6, bx + br + 8, by + br + 8), fill=(20, 14, 10, 180))
# Chrome sphere body
d.ellipse((bx - br, by - br, bx + br, by + br), fill=(210, 220, 230), outline=(140, 150, 165), width=2)
# Specular shine
d.ellipse((bx - br + 5, by - br + 5, bx - br + 14, by - br + 14), fill=(255, 255, 255))

# Gyro tilt arrows
d.arc((36, 36, 80, 80), start=180, end=270, fill=(255, 200, 80), width=4)
d.polygon([(82, 58), (82, 36), (60, 36)], fill=(255, 200, 80))

im.save(str(root / 'assets/icon.png'))
print('Assets generated successfully.')
