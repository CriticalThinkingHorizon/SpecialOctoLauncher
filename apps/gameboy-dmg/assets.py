from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math
import struct

root = Path(__file__).resolve().parent
(root / 'assets').mkdir(exist_ok=True)
(root / 'shaders').mkdir(exist_ok=True)

FONT_CANDIDATES = [
    str((root.parent.parent / 'fonts' / 'fixedsys.ttf').resolve()),
    'C:/Windows/Fonts/consola.ttf',
    'C:/Windows/Fonts/cour.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
]
font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
if font_path is None:
    raise SystemExit('No monospace TrueType font found.')

FONT_SIZE = 30
ATLAS_W, ATLAS_H = 1024, 2048
FIRST, LAST = 32, 126

font = ImageFont.truetype(font_path, FONT_SIZE)
ascent, descent = font.getmetrics()
CELL_W = math.ceil(font.getlength('M')) + 2
CELL_H = ascent + descent + 2
COLS = ATLAS_W // CELL_W

atlas = Image.new('L', (ATLAS_W, ATLAS_H), 0)
draw = ImageDraw.Draw(atlas)
for code in range(FIRST, LAST + 1):
    idx = code - FIRST
    x = (idx % COLS) * CELL_W
    y = (idx // COLS) * CELL_H
    draw.text((x + 1, y + 1), chr(code), font=font, fill=255)

(root / 'assets/text.bin').write_bytes(atlas.tobytes())
(root / 'shaders/text.glsl').write_text(
    '// Generated by assets.py. Do not edit.\n'
    f'const int GLYPH_W = {CELL_W};\n'
    f'const int GLYPH_H = {CELL_H};\n'
    f'const int GLYPH_COLS = {COLS};\n'
    f'const uint GLYPH_FIRST = {FIRST}u;\n'
    f'const uint GLYPH_COUNT = {LAST - FIRST + 1}u;\n'
)

# Initial state (1024 bytes)
state = bytearray(1024)
# c.game: x = state (0=play), y = score (0), z = coins (0), w = lives (3)
state[784:800] = struct.pack('<IIII', 0, 0, 0, 3)
# c.flow: player X (32.0), player Y (96.0), vel X (0.0), vel Y (0.0)
state[816:832] = struct.pack('<ffff', 32.0, 96.0, 0.0, 0.0)
# c.piece: scrollX (0), animFrame (0), facing (1), onGround (1)
state[800:816] = struct.pack('<iiii', 0, 0, 1, 1)
# c.transition: paletteMode (0 = Classic Green, 1 = Pocket Gray), batteryLevel (1.0), spare, spare
state[960:976] = struct.pack('<ffff', 0.0, 1.0, 0.0, 0.0)
# c.stats: enemy1 X (140), enemy1 dir (-1), enemy2 X (260), enemy2 dir (-1)
state[992:1008] = struct.pack('<IIII', 140, 1, 260, 1)

(root / 'assets/state.bin').write_bytes(bytes(state))

# Generate high-contrast GameBoy DMG-01 Icon (256x256)
im = Image.new('RGBA', (256, 256), (18, 20, 22, 255))
d = ImageDraw.Draw(im)

# Classic DMG Off-white / Gray chassis
d.rounded_rectangle((24, 12, 232, 244), radius=22, fill=(215, 212, 205), outline=(160, 158, 150), width=4)

# Top grooved lines
d.line([(44, 20), (212, 20)], fill=(160, 158, 150), width=2)
d.line([(44, 25), (212, 25)], fill=(160, 158, 150), width=2)

# Bezel Screen Frame (Dark Gray with blue & magenta stripe)
d.rounded_rectangle((38, 38, 218, 145), radius=10, fill=(115, 120, 128), outline=(80, 84, 90), width=3)
d.line([(48, 46), (208, 46)], fill=(130, 40, 100), width=2) # Magenta stripe
d.line([(48, 50), (208, 50)], fill=(40, 60, 130), width=2)  # Blue stripe

# Red Battery Indicator LED
d.ellipse((50, 84, 56, 90), fill=(240, 40, 40))

# LCD Dot-Matrix Display (Classic Olive Green)
d.rectangle((70, 56, 186, 134), fill=(155, 188, 15), outline=(139, 172, 15), width=2)

# Pixel art character on LCD
d.rectangle((100, 94, 114, 114), fill=(15, 56, 15)) # Body
d.rectangle((104, 82, 110, 94), fill=(48, 98, 48))  # Head
d.rectangle((140, 104, 152, 114), fill=(15, 56, 15)) # Slime enemy

# D-Pad (Classic Matte Black Cross)
d.rectangle((52, 168, 88, 184), fill=(40, 40, 44))
d.rectangle((62, 158, 78, 194), fill=(40, 40, 44))
d.ellipse((68, 174, 72, 178), fill=(25, 25, 28)) # Center dimple

# A & B Buttons (Magenta / Burgundy angled pills)
d.ellipse((152, 178, 172, 198), fill=(150, 30, 80), outline=(110, 20, 60), width=2) # B
d.ellipse((184, 162, 204, 182), fill=(150, 30, 80), outline=(110, 20, 60), width=2) # A

# Select & Start (Angled gray rubber pills)
d.polygon([(92, 218), (108, 212), (111, 218), (95, 224)], fill=(130, 132, 138))
d.polygon([(122, 218), (138, 212), (141, 218), (125, 224)], fill=(130, 132, 138))

# Speaker slots
for sx, sy in [(175, 212), (185, 216), (195, 220), (205, 224)]:
    d.line([(sx, sy), (sx + 14, sy + 14)], fill=(160, 158, 150), width=3)

im.save(str(root / 'assets/icon.png'))
print('GameBoy DMG assets generated successfully.')
