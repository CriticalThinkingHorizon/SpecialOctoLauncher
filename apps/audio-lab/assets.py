from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math
import struct

root = Path(__file__).resolve().parent
(root / 'assets').mkdir(exist_ok=True)
(root / 'shaders').mkdir(exist_ok=True)

FONT_CANDIDATES = [
    str((root.parent.parent / 'fonts' / 'fixedsys.ttf').resolve()),
    'C:/Windows/Fonts/consola.ttf',
    'C:/Windows/Fonts/cour.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
]
font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
if font_path is None:
    raise SystemExit('No monospace TrueType font found.')

FONT_SIZE = 30
ATLAS_W, ATLAS_H = 1024, 2048
FIRST, LAST = 32, 126

font = ImageFont.truetype(font_path, FONT_SIZE)
ascent, descent = font.getmetrics()
CELL_W = math.ceil(font.getlength('M')) + 2
CELL_H = ascent + descent + 2
COLS = ATLAS_W // CELL_W

atlas = Image.new('L', (ATLAS_W, ATLAS_H), 0)
draw = ImageDraw.Draw(atlas)
for code in range(FIRST, LAST + 1):
    idx = code - FIRST
    x = (idx % COLS) * CELL_W
    y = (idx // COLS) * CELL_H
    draw.text((x + 1, y + 1), chr(code), font=font, fill=255)

(root / 'assets/text.bin').write_bytes(atlas.tobytes())
(root / 'shaders/text.glsl').write_text(
    '// Generated by assets.py. Do not edit.\n'
    f'const int GLYPH_W = {CELL_W};\n'
    f'const int GLYPH_H = {CELL_H};\n'
    f'const int GLYPH_COLS = {COLS};\n'
    f'const uint GLYPH_FIRST = {FIRST}u;\n'
    f'const uint GLYPH_COUNT = {LAST - FIRST + 1}u;\n'
)

# Initial state (1024 bytes)
state = bytearray(1024)
# c.game: uvec4(mode=0 (soundboard), selectedSfx=0, volume=85, waveType=0)
# c.piece: ivec4(freq=440, duration=200, octave=4, activePlaying=0)
# c.flow: vec4(bannerTimer=0, wavePhase=0, peakL=0, peakR=0)
state[784:800] = struct.pack('<IIII', 0, 0, 85, 0)
state[800:816] = struct.pack('<iiii', 440, 200, 4, 0)
state[816:832] = struct.pack('<ffff', 0.0, 0.0, 0.0, 0.0)
state[960:964] = b'\x00\x00\x80\x3f'
(root / 'assets/state.bin').write_bytes(bytes(state))

# Generate sleek Audio Lab icon with speaker & glowing audio waveform
im = Image.new('RGBA', (256, 256), (12, 16, 28, 255))
d = ImageDraw.Draw(im)

# Outer rounded rectangle
d.rounded_rectangle((16, 16, 240, 240), radius=28, fill=(18, 24, 40), outline=(0, 230, 200), width=6)

# Glowing speaker cone / audio wave motif
cx, cy = 128, 128

# Speaker body
d.polygon([(64, 100), (96, 100), (136, 70), (136, 186), (96, 156), (64, 156)], fill=(0, 210, 220))
d.rectangle((64, 100, 96, 156), fill=(0, 160, 200))

# Concentric audio wave arcs
d.arc((110, 94, 170, 162), start=-50, end=50, fill=(0, 255, 180), width=5)
d.arc((95, 76, 200, 180), start=-55, end=55, fill=(0, 230, 240), width=5)
d.arc((80, 56, 230, 200), start=-58, end=58, fill=(80, 200, 255), width=6)

# Bottom audio visualizer equalizer bars
for i, h in enumerate([18, 36, 22, 48, 28, 42, 16]):
    bx = 68 + i * 18
    d.rounded_rectangle((bx, 218 - h, bx + 12, 218), radius=3, fill=(0, 240, 200))

im.save(root / 'assets/icon.png')
print("Audio Lab assets generated successfully.")
