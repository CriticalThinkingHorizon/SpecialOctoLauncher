from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math
import struct

root = Path(__file__).resolve().parent
(root / 'assets').mkdir(exist_ok=True)
(root / 'shaders').mkdir(exist_ok=True)

FONT_CANDIDATES = [
    str((root.parent.parent / 'fonts' / 'fixedsys.ttf').resolve()),
    'C:/Windows/Fonts/consola.ttf',
    'C:/Windows/Fonts/cour.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
]
font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
if font_path is None:
    raise SystemExit('No monospace TrueType font found.')

FONT_SIZE = 30
ATLAS_W, ATLAS_H = 1024, 2048
FIRST, LAST = 32, 126

font = ImageFont.truetype(font_path, FONT_SIZE)
ascent, descent = font.getmetrics()
CELL_W = math.ceil(font.getlength('M')) + 2
CELL_H = ascent + descent + 2
COLS = ATLAS_W // CELL_W

atlas = Image.new('L', (ATLAS_W, ATLAS_H), 0)
draw = ImageDraw.Draw(atlas)
for code in range(FIRST, LAST + 1):
    idx = code - FIRST
    x = (idx % COLS) * CELL_W
    y = (idx // COLS) * CELL_H
    draw.text((x + 1, y + 1), chr(code), font=font, fill=255)

(root / 'assets/text.bin').write_bytes(atlas.tobytes())
(root / 'shaders/text.glsl').write_text(
    '// Generated by assets.py. Do not edit.\n'
    f'const int GLYPH_W = {CELL_W};\n'
    f'const int GLYPH_H = {CELL_H};\n'
    f'const int GLYPH_COLS = {COLS};\n'
    f'const uint GLYPH_FIRST = {FIRST}u;\n'
    f'const uint GLYPH_COUNT = {LAST - FIRST + 1}u;\n'
)

# Initial state (1024 bytes)
state = bytearray(1024)
# c.game: x = state (0), y = kills (0), z = weapon timer (0), w = health (100)
state[784:800] = struct.pack('<IIII', 0, 0, 0, 100)
# c.flow: player posX (2.5), posY (2.5), dirAngle (0.0 rad), ammo (32.0)
state[816:832] = struct.pack('<ffff', 2.5, 2.5, 0.0, 32.0)
# c.piece: door1 (0), door2 (0), door3 (0), spare (0)
state[800:816] = struct.pack('<iiii', 0, 0, 0, 0)
# c.transition: headBob (0.0), damageFlash (0.0), recoil (0.0), spare (0.0)
state[960:976] = struct.pack('<ffff', 0.0, 0.0, 0.0, 0.0)
# c.stats: enemy1 alive(1), enemy2 alive(1), enemy3 alive(1), enemy4 alive(1)
state[992:1008] = struct.pack('<IIII', 1, 1, 1, 1)

(root / 'assets/state.bin').write_bytes(bytes(state))

# Generate high-contrast Wolfenstein 3D Icon (256x256)
im = Image.new('RGBA', (256, 256), (18, 12, 14, 255))
d = ImageDraw.Draw(im)

# Outer metallic beveled frame with red/gold military trim
d.rounded_rectangle((12, 12, 244, 244), radius=28, fill=(30, 20, 22), outline=(180, 40, 40), width=6)
d.rounded_rectangle((26, 26, 230, 230), radius=16, fill=(16, 12, 16), outline=(220, 180, 50), width=3)

# Brick wall background in 3D perspective
d.polygon([(36, 40), (128, 70), (128, 180), (36, 210)], fill=(75, 78, 88), outline=(50, 52, 60))
d.polygon([(220, 40), (128, 70), (128, 180), (220, 210)], fill=(55, 58, 68), outline=(40, 42, 50))
d.polygon([(36, 210), (128, 180), (220, 210), (128, 226)], fill=(35, 30, 30))

# Blue stone accents & gold eagle emblem silhouette
d.rectangle((100, 80, 156, 130), fill=(20, 40, 90), outline=(180, 140, 30), width=2)
# Eagle / Star
d.polygon([(128, 86), (138, 105), (150, 95), (142, 115), (128, 122), (114, 115), (106, 95), (118, 105)], fill=(240, 200, 60))

# Pistol Barrel pointing forward
d.polygon([(112, 230), (124, 150), (132, 150), (144, 230)], fill=(90, 95, 105), outline=(50, 52, 60))
d.rectangle((122, 145, 134, 160), fill=(40, 42, 48), outline=(160, 170, 180), width=2)
# Muzzle Flash star
d.polygon([(128, 130), (133, 142), (145, 145), (133, 148), (128, 160), (123, 148), (111, 145), (123, 142)], fill=(255, 230, 80))
d.ellipse((124, 141, 132, 149), fill=(255, 255, 220))

# Text "WOLF 3D"
d.text((58, 32), "WOLF 3D", font=font, fill=(255, 210, 60))

im.save(str(root / 'assets/icon.png'))
print('Wolfenstein 3D assets generated successfully.')
