from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math

root = Path(__file__).resolve().parent
(root / 'assets').mkdir(exist_ok=True)
(root / 'shaders').mkdir(exist_ok=True)

FONT_CANDIDATES = [
    'C:/Windows/Fonts/consola.ttf',
    'C:/Windows/Fonts/cour.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
]
font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
if font_path is None:
    raise SystemExit('No monospace TrueType font found.')

FONT_SIZE = 30
ATLAS_W, ATLAS_H = 1024, 2048
FIRST, LAST = 32, 126

font = ImageFont.truetype(font_path, FONT_SIZE)
ascent, descent = font.getmetrics()
CELL_W = math.ceil(font.getlength('M')) + 2
CELL_H = ascent + descent + 2
COLS = ATLAS_W // CELL_W

atlas = Image.new('L', (ATLAS_W, ATLAS_H), 0)
draw = ImageDraw.Draw(atlas)
for code in range(FIRST, LAST + 1):
    idx = code - FIRST
    x = (idx % COLS) * CELL_W
    y = (idx // COLS) * CELL_H
    draw.text((x + 1, y + 1), chr(code), font=font, fill=255)

(root / 'assets/text.bin').write_bytes(atlas.tobytes())
(root / 'shaders/text.glsl').write_text(
    '// Generated by assets.py. Do not edit.\n'
    f'const int GLYPH_W = {CELL_W};\n'
    f'const int GLYPH_H = {CELL_H};\n'
    f'const int GLYPH_COLS = {COLS};\n'
    f'const uint GLYPH_FIRST = {FIRST}u;\n'
    f'const uint GLYPH_COUNT = {LAST - FIRST + 1}u;\n'
)

state = bytearray(1024)
state[960:964] = b'\x00\x00\x80\x3f'
(root / 'assets/state.bin').write_bytes(bytes(state))

# Retro CHIP-8 Icon: dark chassis with green phosphor pixel display and D-pad
im = Image.new('RGBA', (256, 256), (16, 20, 18, 255))
d = ImageDraw.Draw(im)
d.rounded_rectangle((24, 24, 232, 232), radius=32, fill=(24, 32, 28), outline=(60, 220, 100), width=6)
# CRT screen area
d.rounded_rectangle((48, 48, 208, 160), radius=12, fill=(10, 24, 14), outline=(40, 160, 80), width=4)
# Space Invader / Pixel Sprite in phosphor green
pixels = [
    (100, 75), (156, 75),
    (114, 89), (142, 89),
    (100, 103), (114, 103), (128, 103), (142, 103), (156, 103),
    (86, 117), (100, 117), (128, 117), (156, 117), (170, 117),
    (86, 131), (114, 131), (142, 131), (170, 131),
    (100, 145), (156, 145)
]
for px, py in pixels:
    d.rectangle((px - 5, py - 5, px + 5, py + 5), fill=(80, 255, 120))

# D-Pad indicator at bottom left
d.rectangle((66, 182, 86, 214), fill=(60, 80, 70))
d.rectangle((50, 192, 102, 204), fill=(60, 80, 70))
# Buttons at bottom right
d.ellipse((168, 190, 186, 208), fill=(220, 60, 80))
d.ellipse((190, 180, 208, 198), fill=(80, 180, 240))

im.save(root / 'assets/icon.png')
