from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math

root = Path(__file__).resolve().parent
(root / 'assets').mkdir(exist_ok=True)
(root / 'shaders').mkdir(exist_ok=True)

FONT_CANDIDATES = [
    str((root.parent.parent / 'fonts' / 'fixedsys.ttf').resolve()),
    'C:/Windows/Fonts/consola.ttf',
    'C:/Windows/Fonts/cour.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
]
font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
if font_path is None:
    raise SystemExit('No monospace TrueType font found.')

FONT_SIZE = 30
ATLAS_W, ATLAS_H = 1024, 2048
FIRST, LAST = 32, 126

font = ImageFont.truetype(font_path, FONT_SIZE)
ascent, descent = font.getmetrics()
CELL_W = math.ceil(font.getlength('M')) + 2
CELL_H = ascent + descent + 2
COLS = ATLAS_W // CELL_W

atlas = Image.new('L', (ATLAS_W, ATLAS_H), 0)
draw = ImageDraw.Draw(atlas)
for code in range(FIRST, LAST + 1):
    idx = code - FIRST
    x = (idx % COLS) * CELL_W
    y = (idx // COLS) * CELL_H
    draw.text((x + 1, y + 1), chr(code), font=font, fill=255)

(root / 'assets/text.bin').write_bytes(atlas.tobytes())
(root / 'shaders/text.glsl').write_text(
    '// Generated by assets.py. Do not edit.\n'
    f'const int GLYPH_W = {CELL_W};\n'
    f'const int GLYPH_H = {CELL_H};\n'
    f'const int GLYPH_COLS = {COLS};\n'
    f'const uint GLYPH_FIRST = {FIRST}u;\n'
    f'const uint GLYPH_COUNT = {LAST - FIRST + 1}u;\n'
)

state = bytearray(1024)
state[960:964] = b'\x00\x00\x80\x3f'
(root / 'assets/state.bin').write_bytes(bytes(state))

# Generate high-contrast firmware update / flash chip icon
im = Image.new('RGBA', (256, 256), (16, 20, 30, 255))
d = ImageDraw.Draw(im)

# Outer rounded bezel
d.rounded_rectangle((16, 16, 240, 240), radius=28, fill=(20, 30, 48), outline=(60, 160, 240), width=6)

# IC Chip package
d.rectangle((56, 56, 200, 200), fill=(28, 42, 64), outline=(100, 200, 255), width=4)

# Chip pins (top & bottom)
for x in (76, 102, 128, 154, 180):
    d.rectangle((x - 4, 42, x + 4, 56), fill=(180, 220, 255))
    d.rectangle((x - 4, 200, x + 4, 214), fill=(180, 220, 255))

# Chip pins (left & right)
for y in (76, 102, 128, 154, 180):
    d.rectangle((42, y - 4, 56, y + 4), fill=(180, 220, 255))
    d.rectangle((200, y - 4, 214, y + 4), fill=(180, 220, 255))

# Upward update arrow inside chip
d.polygon([(128, 80), (96, 124), (114, 124), (114, 166), (142, 166), (142, 124), (160, 124)], fill=(80, 240, 180))

# Badge text "BOOT UPDATE"
try:
    badge_font = ImageFont.truetype(font_path, 16)
    d.text((70, 172), 'TNS2 FLASH', font=badge_font, fill=(200, 240, 255))
except Exception:
    pass

im.save(root / 'assets/icon.png')
print('Bootstrap updater assets generated successfully.')
