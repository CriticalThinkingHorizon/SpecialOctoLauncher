from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math

root = Path(__file__).resolve().parent
(root / 'assets').mkdir(exist_ok=True)
(root / 'shaders').mkdir(exist_ok=True)

FONT_CANDIDATES = [
    str((root.parent.parent / 'fonts' / 'fixedsys.ttf').resolve()),
    'C:/Windows/Fonts/consola.ttf',
    'C:/Windows/Fonts/cour.ttf',
    '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
]
font_path = next((p for p in FONT_CANDIDATES if Path(p).exists()), None)
if font_path is None:
    raise SystemExit('No monospace TrueType font found.')

FONT_SIZE = 30
ATLAS_W, ATLAS_H = 1024, 2048
FIRST, LAST = 32, 126

font = ImageFont.truetype(font_path, FONT_SIZE)
ascent, descent = font.getmetrics()
CELL_W = math.ceil(font.getlength('M')) + 2
CELL_H = ascent + descent + 2
COLS = ATLAS_W // CELL_W

atlas = Image.new('L', (ATLAS_W, ATLAS_H), 0)
draw = ImageDraw.Draw(atlas)
for code in range(FIRST, LAST + 1):
    idx = code - FIRST
    x = (idx % COLS) * CELL_W
    y = (idx // COLS) * CELL_H
    draw.text((x + 1, y + 1), chr(code), font=font, fill=255)

(root / 'assets/text.bin').write_bytes(atlas.tobytes())
(root / 'shaders/text.glsl').write_text(
    '// Generated by assets.py. Do not edit.\n'
    f'const int GLYPH_W = {CELL_W};\n'
    f'const int GLYPH_H = {CELL_H};\n'
    f'const int GLYPH_COLS = {COLS};\n'
    f'const uint GLYPH_FIRST = {FIRST}u;\n'
    f'const uint GLYPH_COUNT = {LAST - FIRST + 1}u;\n'
)

# Initial state: ball at center (960, 540), vel (+8, +4), paddles at 540, AI mode enabled (1)
import struct
state = bytearray(1024)
# c.game: scoreLeft=0, scoreRight=0, gameState=0, aiMode=1
state[784:800] = struct.pack('<IIII', 0, 0, 0, 1)
# c.piece: ballX*10 = 9600, ballY*10 = 5400, ballVelX*10 = 70, ballVelY*10 = 35
state[800:816] = struct.pack('<iiii', 9600, 5400, 70, 35)
# c.flow: paddleLeftY = 540.0, paddleRightY = 540.0, rally = 0.0, timer = 0.0
state[816:832] = struct.pack('<ffff', 540.0, 540.0, 0.0, 0.0)
# c.bagMeta: paddleH = 160.0, paddleW = 28.0, leftX = 160.0, rightX = 1760.0
state[832:848] = struct.pack('<ffff', 160.0, 28.0, 160.0, 1760.0)

state[960:964] = b'\x00\x00\x80\x3f'
(root / 'assets/state.bin').write_bytes(bytes(state))

# Generate sleek Retro Pong icon with neon paddles & glowing ball
im = Image.new('RGBA', (256, 256), (12, 16, 22, 255))
d = ImageDraw.Draw(im)

# Outer neon green rounded rectangle
d.rounded_rectangle((16, 16, 240, 240), radius=28, fill=(16, 28, 36), outline=(40, 220, 140), width=6)

# Center dotted line
for y in range(40, 216, 24):
    d.line([(128, y), (128, y + 12)], fill=(60, 120, 90), width=4)

# Left paddle (cyan)
d.rounded_rectangle((48, 80, 62, 160), radius=4, fill=(50, 220, 240), outline=(120, 255, 255), width=2)

# Right paddle (pink / magenta)
d.rounded_rectangle((194, 110, 208, 190), radius=4, fill=(240, 60, 140), outline=(255, 120, 190), width=2)

# Glowing square ball
d.rectangle((116, 116, 132, 132), fill=(255, 255, 255), outline=(180, 255, 200), width=2)

# Score numbers
try:
    s_font = ImageFont.truetype(font_path, 36)
    d.text((80, 44), "3", font=s_font, fill=(50, 220, 240))
    d.text((156, 44), "1", font=s_font, fill=(240, 60, 140))
except Exception:
    pass

im.save(root / 'assets/icon.png')
print('Pong assets generated successfully.')
